#!/usr/bin/env bash
# GENERATES preserve-counts.txt: each PRESERVE row's MEASURED baseline site count. Never typed.
set -uo pipefail
D="$(cd "$(dirname "$0")" && pwd)"; R="${1:?tree root}"
echo "# GENERATED by gen-preserve-counts.sh $R at $(date -u +%Y-%m-%dT%H:%M:%SZ) — do not hand-edit."
grep -v '^#' "$D/criteria.tsv" | awk -F'\t' '$2=="PRESERVE"{print $1}' | while read -r id; do
  n=$(python3 "$D/checklib.py" "$R" "$D/criteria.tsv" "$id" | awk -v i="$id" '$2==i{for(j=1;j<=NF;j++) if($j ~ /^measured_sites=/){split($j,a,"=");print a[2]}}')
  echo "$id ${n:-0}"
done
