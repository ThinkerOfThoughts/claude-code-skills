#!/usr/bin/env bash
# gen-criteria-table.sh <tree-root> — emits 1.5-criteria.md §1's table. The SITES column is MEASURED by
# checklib.py --sites, never typed: reviewer F/1's pass-2 blocker was "the measured site sets are not the
# measurement" (four gating rows contradicted the very file they cited as their authority).
# Exits 1 if any NEW/COOC row measures zero sites (a criterion that asserts nothing), 2 on misalignment.
set -uo pipefail
D="$(cd "$(dirname "$0")" && pwd)"; R="${1:?tree root}"
T=$(mktemp -d); trap 'rm -rf "$T"' EXIT
python3 "$D/checklib.py" "$R" "$D/criteria.tsv" --sites > "$T/sites"
grep -v '^#' "$D/criteria.tsv" > "$T/rows"
[ "$(wc -l < "$T/sites")" = "$(wc -l < "$T/rows")" ] || { echo "FATAL: row count mismatch" >&2; exit 2; }
echo "<!-- GENERATED by oracles/gen-criteria-table.sh $R at $(date -u +%Y-%m-%dT%H:%M:%SZ) — do not hand-edit rows. -->"
echo "| # | Criterion | Kind | Gating | SITES — **measured**, generated by \`check.sh . --sites\` | PINNED STRING (verbatim; normalized substring) | Paired absence (must appear NOWHERE in CORPUS) |"
echo "|---|---|---|---|---|---|---|"
n=0; rc=0
while IFS= read -r sline && IFS= read -r cline <&3; do
  IFS=$'\t' read -r sid skind scount ssites <<<"$sline"
  IFS=$'\t' read -r cid ckind cpat cpin cabs <<<"$cline"
  [ "$sid" = "$cid" ] || { echo "FATAL row misalignment: $sid vs $cid" >&2; exit 2; }
  n=$((n+1))
  if [ "$skind" = NEW ] && [ "${scount:-0}" -eq 0 ]; then
    echo "VACUOUS-NEW $sid measures 0 sites in $R — an obligation row with no anchor in the OLD text" >&2; rc=1
  elif [ "$skind" = COOC ] && [ "${scount:-0}" -eq 0 ]; then
    echo "INFO $sid (COOC) measures 0 sites in $R — EXPECTED before the build; check.sh still FAILS the row there, which is what makes it discriminate" >&2; fi
  printf '| %s | **%s** | %s | gating | %s *(%s)* | `%s` | %s |\n' \
    "$n" "$cid" "$ckind" "$ssites" "$scount" "$cpin" "${cabs:-—}"
done < "$T/sites" 3< "$T/rows"
echo
echo "ROWS EMITTED: $n — SITES columns produced from measurement, not typed. Anchor EREs: oracles/criteria.tsv."
[ $rc -eq 0 ] && echo "CRITERIA-TABLE: OK — every NEW obligation row has a measured anchor in this tree"
[ $rc -ne 0 ] && echo "CRITERIA-TABLE: FAIL — a NEW obligation row measures zero sites and therefore asserts nothing"
exit $rc
