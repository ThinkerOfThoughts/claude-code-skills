#!/usr/bin/env bash
# GENERATES oracles/expected-sites.txt from the tree itself. Nothing here is hand-typed:
# the expectation is the MEASURED baseline site set, with phantom hits excluded and reported.
# Usage: gen-expected-sites.sh <tree-root> > expected-sites.txt
set -uo pipefail
. "$(dirname "$0")/lib-corpus.sh"
R="${1:?tree root}"
echo "# GENERATED by oracles/gen-expected-sites.sh — do not hand-edit."
echo "# command: $0 $R"
echo "# generated: $(date -u +%Y-%m-%dT%H:%M:%SZ)"
echo "# format: <ID> <space-separated relative file paths>"
for id in $LIVE_IDS; do
  files=$(corpus_paths "$R" | while read -r f; do
    while IFS=: read -r ln _; do
      line=$(sed -n "${ln}p" "$f")
      # PHANTOM EXCLUSION, reported on stderr not silently dropped
      if [ "$id" = TOP ] && printf '%s' "$line" | grep -q 'ON TOP OF' && ! printf '%s' "$line" | grep -qE '\(TOP\)|\*\*TOP\*\*'; then
        echo "PHANTOM-EXCLUDED $id ${f#$R/}:$ln [ON TOP OF]" >&2; continue
      fi
      echo "${f#$R/}"
    done < <(grep -now -- "$id" "$f" 2>/dev/null)
  done | sort -u | tr '\n' ' ')
  echo "$id $files"
done
